"""Content-focused Persian word-cloud helpers.

The stopword collection intentionally lives in this small, isolated module.
An administrator or developer can extend ``PERSIAN_STOPWORDS`` without
touching the dashboard aggregation query or any presentation code.
"""

from __future__ import annotations

import re
from collections import Counter


# Keep this collection in one place so it is easy to expand for a newsroom's
# own recurring, low-information vocabulary.  Both normal and half-space
# variants are compared by ``_comparison_form`` below.
